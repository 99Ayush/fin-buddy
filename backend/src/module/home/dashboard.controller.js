'use strict';

const reportStore = require('../../shared/reportStore');

// ── Helpers ──────────────────────────────────────────────────────────────────

/**
 * Derive next-best-action items from the user's report list.
 * Rule-based only — no LLM involvement.
 */
function deriveNextSteps(reports, user) {
  const steps = [];

  if (!reports || reports.length === 0) {
    steps.push({
      id: 'upload-doc',
      icon: '📄',
      title: 'Upload your first document',
      description: 'Add an offer letter or payslip to get personalised insights.',
      route: '/documents',
      priority: 1,
    });
  }

  const hasOfferLetter = reports.some(r => r.documentType === 'offer_letter');
  const hasPayslip     = reports.some(r => r.documentType === 'payslip');

  if (!hasOfferLetter) {
    steps.push({
      id: 'upload-offer',
      icon: '💼',
      title: 'Analyse an offer letter',
      description: 'Upload an offer letter to check for predatory clauses and calculate in-hand salary.',
      route: '/documents',
      priority: 2,
    });
  }

  if (!hasPayslip) {
    steps.push({
      id: 'upload-payslip',
      icon: '🧾',
      title: 'Upload a payslip',
      description: 'A payslip helps verify your current CTC and tax deductions.',
      route: '/documents',
      priority: 3,
    });
  }

  steps.push({
    id: 'compare-offers',
    icon: '⚖️',
    title: 'Compare job offers',
    description: 'Place multiple offers side-by-side and see which package is genuinely better.',
    route: '/offers',
    priority: 4,
  });

  steps.push({
    id: 'salary-tax',
    icon: '💰',
    title: 'Check salary & tax regime',
    description: 'Compare Old vs New tax regime to find which saves you more money.',
    route: '/salarytax',
    priority: 5,
  });

  steps.push({
    id: 'money-plan',
    icon: '📈',
    title: 'Plan your finances',
    description: 'Set savings goals, track SIPs, and plan for major life expenses.',
    route: '/moneyplan',
    priority: 6,
  });

  // Sort by priority, return top 4
  return steps.sort((a, b) => a.priority - b.priority).slice(0, 4);
}

/**
 * Derive timeline events from reports.
 */
function deriveTimeline(reports) {
  if (!reports || reports.length === 0) return [];

  return reports
    .map(r => {
      const base = {
        id: r.documentId,
        date: r.savedAt,
        type: r.documentType || 'document',
      };

      if (r.documentType === 'offer_letter') {
        return {
          ...base,
          icon: '📄',
          title: 'Offer letter analysed',
          description: r.metadata?.sourceFileName
            ? `File: ${r.metadata.sourceFileName}`
            : 'Offer letter uploaded and analysed.',
        };
      }
      if (r.documentType === 'payslip') {
        return {
          ...base,
          icon: '🧾',
          title: 'Payslip uploaded',
          description: r.metadata?.sourceFileName
            ? `File: ${r.metadata.sourceFileName}`
            : 'Payslip uploaded and verified.',
        };
      }
      return {
        ...base,
        icon: '📁',
        title: 'Document uploaded',
        description: r.metadata?.sourceFileName || 'A document was uploaded.',
      };
    })
    .sort((a, b) => new Date(b.date) - new Date(a.date)); // newest first
}

// ── Controllers ───────────────────────────────────────────────────────────────

/**
 * GET /api/home/overview
 * Returns profile summary and document counts. No fabricated financial figures.
 */
async function overview(req, res) {
  try {
    const userId  = req.user.id;
    const reports = await reportStore.listReports(userId);

    const docCounts = { total: reports.length, offer_letter: 0, payslip: 0, other: 0 };
    for (const r of reports) {
      if (r.documentType === 'offer_letter') docCounts.offer_letter++;
      else if (r.documentType === 'payslip') docCounts.payslip++;
      else docCounts.other++;
    }

    return res.json({
      user: req.user,
      documents: docCounts,
      hasData: reports.length > 0,
      // Financial summaries deliberately absent — owned by P1/P2 modules
      financialSummary: null,
      note: 'Financial metrics are generated by the Documents and Salary & Tax modules.',
    });
  } catch (err) {
    console.error('[home/overview]', err.message);
    return res.status(500).json({ error: 'Could not load overview.' });
  }
}

/**
 * GET /api/home/timeline
 * Returns chronological document events for the user.
 */
async function timeline(req, res) {
  try {
    const userId      = req.user.id;
    const fullReports = await reportStore.listFullReports(userId);
    const events      = deriveTimeline(fullReports);

    return res.json({ events, total: events.length });
  } catch (err) {
    console.error('[home/timeline]', err.message);
    return res.status(500).json({ error: 'Could not load timeline.' });
  }
}

/**
 * GET /api/home/activity
 * Returns recent document activity for the user.
 */
async function activity(req, res) {
  try {
    const userId  = req.user.id;
    const reports = await reportStore.listReports(userId);

    const items = reports
      .sort((a, b) => new Date(b.savedAt) - new Date(a.savedAt))
      .slice(0, 10)
      .map(r => ({
        id: r.documentId,
        type: r.documentType || 'document',
        label: r.documentType === 'offer_letter' ? 'Offer letter analysed'
             : r.documentType === 'payslip'      ? 'Payslip uploaded'
             : 'Document uploaded',
        fileName: r.sourceFileName || null,
        date: r.savedAt,
      }));

    return res.json({ activity: items, total: items.length });
  } catch (err) {
    console.error('[home/activity]', err.message);
    return res.status(500).json({ error: 'Could not load activity.' });
  }
}

/**
 * GET /api/home/next-steps
 * Returns rule-based recommended actions for the user.
 */
async function nextSteps(req, res) {
  try {
    const userId      = req.user.id;
    const fullReports = await reportStore.listFullReports(userId);
    const steps       = deriveNextSteps(fullReports, req.user);

    return res.json({ steps, total: steps.length });
  } catch (err) {
    console.error('[home/next-steps]', err.message);
    return res.status(500).json({ error: 'Could not load next steps.' });
  }
}

module.exports = { overview, timeline, activity, nextSteps };
